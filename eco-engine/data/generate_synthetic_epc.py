def seed_database(db_path: Path) -> None:
    conn = sqlite3.connect(str(db_path))
    cursor = conn.cursor()
    
    # Read and apply schema
    schema_path = db_path.parent / "schema.sql"
    if schema_path.exists():
        with open(schema_path, "r", encoding="utf-8") as f:
            cursor.executescript(f.read())
    else:
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS properties (
                property_id TEXT PRIMARY KEY,
                address TEXT NOT NULL,
                postcode TEXT NOT NULL,
                region TEXT NOT NULL,
                property_type TEXT NOT NULL,
                built_year INTEGER NOT NULL,
                total_floor_area_m2 REAL NOT NULL,
                baseline_value_gbp REAL NOT NULL,
                current_epc_rating TEXT NOT NULL,
                current_epc_score INTEGER NOT NULL,
                current_primary_energy_kwh_m2 REAL NOT NULL,
                wall_type TEXT NOT NULL,
                wall_insulation_status TEXT NOT NULL,
                wall_u_value REAL NOT NULL,
                roof_type TEXT NOT NULL,
                roof_insulation_status TEXT NOT NULL,
                roof_insulation_depth_mm INTEGER NOT NULL,
                floor_type TEXT NOT NULL,
                floor_insulation_status TEXT NOT NULL,
                glazing_type TEXT NOT NULL,
                heating_type TEXT NOT NULL,
                heating_efficiency_pct REAL NOT NULL,
                annual_gas_kwh REAL NOT NULL,
                annual_electricity_kwh REAL NOT NULL,
                solar_pv_kwp REAL DEFAULT 0.0,
                battery_storage_kwh REAL DEFAULT 0.0,
                smart_controls INTEGER DEFAULT 0
            )
        """)

    for p in PROPERTIES:
        cursor.execute("""
            INSERT OR REPLACE INTO properties (
                property_id, address, postcode, region, property_type,
                built_year, total_floor_area_m2, baseline_value_gbp,
                current_epc_rating, current_epc_score, current_primary_energy_kwh_m2,
                wall_type, wall_insulation_status, wall_u_value,
                roof_type, roof_insulation_status, roof_insulation_depth_mm,
                floor_type, floor_insulation_status, glazing_type,
                heating_type, heating_efficiency_pct, annual_gas_kwh,
                annual_electricity_kwh, solar_pv_kwp, battery_storage_kwh,
                smart_controls
            ) VALUES (
                ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?
            )
        """, (
            p["property_id"], p["address"], p["postcode"], p["region"], p["property_type"],
            p["built_year"], p["total_floor_area_m2"], p["baseline_value_gbp"],
            p["current_epc_rating"], p["current_epc_score"], p["current_primary_energy_kwh_m2"],
            p["wall_type"], p["wall_insulation_status"], p["wall_u_value"],
            p["roof_type"], p["roof_insulation_status"], p["roof_insulation_depth_mm"],
            p["floor_type"], p["floor_insulation_status"], p["glazing_type"],
            p["heating_type"], p["heating_efficiency_pct"], p["annual_gas_kwh"],
            p["annual_electricity_kwh"], p["solar_pv_kwp"], p["battery_storage_kwh"],
            1 if p["smart_controls"] else 0
        ))

    conn.commit()
    conn.close()
    print(f"Successfully seeded {len(PROPERTIES)} properties into {db_path}")

